// Generic, spec-driven access to the whole Unanet Platform REST surface.
//
// The dedicated tools cover the self-service and common org-level flows with
// tailored guards. Everything else (1,200+ operations) can be looked up and,
// for read-classified operations, executed through these three tools, which
// are constrained by the committed OpenAPI catalog. There is deliberately no
// generic writer: a write needs a dedicated tool with its own guards.
//
//   unanet_api_search_operations  — find operations by keyword/tag/kind
//   unanet_api_describe_operation — params + request/response schema
//   unanet_api_read               — execute a read-classified operation
//
// The catalog is generated by scripts/build-api-catalog.mjs and loaded lazily
// so servers that never use these tools pay nothing.

import { readFileSync } from "node:fs";
import { z } from "zod";
import { type UnanetAuth, createUnanetClient } from "../auth.js";
import { compact, errorResult } from "../utils/http.js";

type CatalogParam = {
	name: string;
	in: "path" | "query" | "header" | "cookie";
	required: boolean;
	type: string;
	enum?: string[];
	description?: string;
};

export type CatalogOperation = {
	id: string;
	method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE";
	path: string;
	tag: string;
	summary?: string;
	description?: string;
	kind: "read" | "write" | "sensitive";
	params?: CatalogParam[];
	body?: string;
	bodyRequired?: boolean;
	response?: string;
	deprecated?: boolean;
};

type Catalog = {
	specVersion: string | null;
	operationCount: number;
	tags: Record<string, number>;
	operations: CatalogOperation[];
};

type SchemaProperty = {
	name: string;
	type: string;
	required?: boolean;
	readOnly?: boolean;
	enum?: string[];
	description?: string;
};

type SchemaEntry = {
	type?: string;
	extends?: string[];
	oneOf?: string[];
	discriminator?: string;
	properties?: SchemaProperty[];
	enum?: string[];
	description?: string;
};

let catalogCache: Catalog | null = null;
let schemasCache: Record<string, SchemaEntry> | null = null;

function specFileUrl(name: string): URL {
	// dist/tools/ and src/tools/ both sit two levels below the package root.
	return new URL(`../../spec/${name}`, import.meta.url);
}

export function loadCatalog(): Catalog {
	if (!catalogCache) {
		catalogCache = JSON.parse(readFileSync(specFileUrl("api-catalog.json"), "utf8"));
	}
	return catalogCache as Catalog;
}

export function loadSchemas(): Record<string, SchemaEntry> {
	if (!schemasCache) {
		schemasCache = JSON.parse(readFileSync(specFileUrl("api-schemas.json"), "utf8"));
	}
	return schemasCache as Record<string, SchemaEntry>;
}

// The catalog stores spec paths like /rest/me/time; the client auto-prefixes
// /platform/rest for paths starting with "/", so strip the leading /rest.
function clientPath(specPath: string): string {
	return specPath.replace(/^\/rest/, "");
}

function normalizeSpecPath(path: string): string {
	let normalized = path.trim();
	normalized = normalized.replace(/^\/platform\/rest/, "/rest");
	if (!normalized.startsWith("/rest/")) normalized = `/rest${normalized.startsWith("/") ? "" : "/"}${normalized}`;
	return normalized;
}

function schemaRefName(type?: string): string | null {
	if (!type) return null;
	const match = type.match(/^(?:ref:|array<)([A-Za-z0-9_]+)>?$/);
	return match ? match[1] : null;
}

function findOperation(args: { operationId?: string; method?: string; path?: string }) {
	const catalog = loadCatalog();
	if (args.operationId) {
		return catalog.operations.find((op) => op.id === args.operationId) ?? null;
	}
	if (args.method && args.path) {
		const path = normalizeSpecPath(args.path);
		const method = args.method.toUpperCase();
		return (
			catalog.operations.find((op) => op.method === method && op.path === path) ?? null
		);
	}
	return null;
}

function expandSchema(name: string | null, depth: number, seen = new Set<string>()): any {
	if (!name) return null;
	const schemas = loadSchemas();
	const entry = schemas[name];
	if (!entry) return { name, unknown: true };
	if (seen.has(name) || depth <= 0) return { name, ...(entry.enum ? { enum: entry.enum } : {}) };
	seen.add(name);
	const out: any = { name };
	if (entry.description) out.description = entry.description;
	if (entry.extends?.length) out.extends = entry.extends;
	if (entry.oneOf?.length) {
		out.oneOf = entry.oneOf.map((child) => expandSchema(child, depth - 1, new Set(seen)));
		if (entry.discriminator) out.discriminator = entry.discriminator;
	}
	if (entry.enum) out.enum = entry.enum;
	if (entry.properties) {
		out.properties = entry.properties.map((prop) => {
			const nested = schemaRefName(prop.type);
			return compact({
				name: prop.name,
				type: prop.type,
				required: prop.required,
				readOnly: prop.readOnly,
				enum: prop.enum,
				description: prop.description,
				schema:
					nested && depth > 1 ? expandSchema(nested, depth - 1, new Set(seen)) : undefined,
			});
		});
	}
	// Inherited properties for allOf-based models.
	for (const parent of entry.extends ?? []) {
		const parentExpanded = expandSchema(parent, depth - 1, new Set(seen));
		if (parentExpanded?.properties) {
			out.inheritedProperties = [
				...(out.inheritedProperties ?? []),
				...parentExpanded.properties.map((prop: any) => ({ ...prop, from: parent })),
			];
		}
	}
	return out;
}

function fillPath(path: string, pathParams: Record<string, unknown> = {}): { ok: true; path: string } | { ok: false; error: string } {
	const missing: string[] = [];
	const filled = path.replace(/\{([^}]+)\}/g, (_match, name) => {
		const value = pathParams[name];
		if (value === undefined || value === null || value === "") {
			missing.push(name);
			return `{${name}}`;
		}
		return encodeURIComponent(String(value));
	});
	if (missing.length) {
		return { ok: false, error: `Missing path parameter(s): ${missing.join(", ")}` };
	}
	return { ok: true, path: filled };
}

const MAX_RESPONSE_CHARS = 200_000;

// Guard the MCP transport against multi-megabyte responses: cap long arrays
// (top level or under items/) and mark the result as truncated.
function truncateResponse(data: any): { data: any; truncated: boolean } {
	const serialized = JSON.stringify(data);
	if (!serialized || serialized.length <= MAX_RESPONSE_CHARS) return { data, truncated: false };
	const trimArray = (array: any[]) => {
		let kept = array.length;
		while (kept > 1 && JSON.stringify(array.slice(0, kept)).length > MAX_RESPONSE_CHARS) {
			kept = Math.floor(kept / 2);
		}
		return array.slice(0, kept);
	};
	if (Array.isArray(data)) return { data: trimArray(data), truncated: true };
	if (Array.isArray(data?.items)) {
		return { data: { ...data, items: trimArray(data.items) }, truncated: true };
	}
	return { data: `${serialized.slice(0, MAX_RESPONSE_CHARS)}…`, truncated: true };
}

function summarizeOperation(op: CatalogOperation) {
	return compact({
		id: op.id,
		method: op.method,
		path: op.path,
		tag: op.tag,
		kind: op.kind,
		summary: op.summary,
		deprecated: op.deprecated,
	});
}

export const searchApiOperationsTool = {
	name: "unanet_api_search_operations",
	description:
		"Search the full Unanet Platform REST API catalog (1,200+ operations) by keyword, resource group (tag), HTTP method and kind (read/write/sensitive). With no query it returns the list of tags with counts. Use the result's id/method/path with unanet_api_describe_operation or unanet_api_read. Read-only, offline (no Unanet call).",
	inputSchema: z.object({
		query: z
			.string()
			.optional()
			.describe("Keywords matched against path, summary, tag and operationId (all words must match)."),
		tag: z.string().optional().describe("Resource group, e.g. 'Projects', 'Vendor Invoices'."),
		method: z.enum(["GET", "POST", "PUT", "PATCH", "DELETE"]).optional(),
		kind: z.enum(["read", "write", "sensitive"]).optional(),
		pathPrefix: z.string().optional().describe("e.g. /rest/me or /rest/projects"),
		limit: z.number().int().min(1).max(200).optional().default(50),
	}),
	handler: async (args: any, _auth: UnanetAuth) => {
		try {
			const catalog = loadCatalog();
			if (!args.query && !args.tag && !args.method && !args.kind && !args.pathPrefix) {
				return {
					success: true,
					specVersion: catalog.specVersion,
					operationCount: catalog.operationCount,
					tags: Object.entries(catalog.tags)
						.sort((a, b) => b[1] - a[1])
						.map(([tag, count]) => ({ tag, count })),
					hint: "Pass query/tag/kind to list operations.",
				};
			}
			const words = String(args.query ?? "")
				.toLowerCase()
				.split(/\s+/)
				.filter(Boolean);
			const tagNeedle = args.tag?.toLowerCase();
			const prefix = args.pathPrefix ? normalizeSpecPath(args.pathPrefix) : null;
			const matches = catalog.operations.filter((op) => {
				if (args.method && op.method !== args.method) return false;
				if (args.kind && op.kind !== args.kind) return false;
				if (tagNeedle && !op.tag.toLowerCase().includes(tagNeedle)) return false;
				if (prefix && !op.path.startsWith(prefix)) return false;
				if (words.length) {
					const haystack = `${op.path} ${op.summary ?? ""} ${op.description ?? ""} ${op.tag} ${op.id}`.toLowerCase();
					if (!words.every((word) => haystack.includes(word))) return false;
				}
				return true;
			});
			return {
				success: true,
				specVersion: catalog.specVersion,
				totalMatches: matches.length,
				returned: Math.min(matches.length, args.limit),
				operations: matches.slice(0, args.limit).map(summarizeOperation),
			};
		} catch (error) {
			return errorResult(error);
		}
	},
};

export const describeApiOperationTool = {
	name: "unanet_api_describe_operation",
	description:
		"Describe one Unanet API operation from the catalog: parameters, request body schema (expanded), response schema, and whether unanet_api_read may execute it. Identify by operationId, or by method + path. Read-only, offline.",
	inputSchema: z.object({
		operationId: z.string().optional(),
		method: z.enum(["GET", "POST", "PUT", "PATCH", "DELETE"]).optional(),
		path: z.string().optional().describe("Spec path, e.g. /rest/projects/{id}/tasks"),
		schemaDepth: z.number().int().min(1).max(4).optional().default(2),
	}),
	handler: async (args: any, _auth: UnanetAuth) => {
		try {
			const op = findOperation(args);
			if (!op) {
				return {
					success: false,
					error: "Operation not found in the catalog. Use unanet_api_search_operations to locate it.",
				};
			}
			return {
				success: true,
				operation: {
					...op,
					executableWith:
						op.kind === "read"
							? "unanet_api_read"
							: op.kind === "write"
								? "not executable generically; use a dedicated write tool or the Unanet UI"
								: "not executable generically (sensitive: workflow, destructive, credential, bank, configuration); use a dedicated tool",
				},
				requestBodySchema: expandSchema(schemaRefName(op.body), args.schemaDepth),
				responseSchema: expandSchema(schemaRefName(op.response), Math.min(args.schemaDepth, 2)),
			};
		} catch (error) {
			return errorResult(error);
		}
	},
};

const executeCommonFields = {
	operationId: z.string().optional().describe("Catalog operationId (preferred)."),
	method: z.enum(["GET", "POST", "PUT", "PATCH", "DELETE"]).optional(),
	path: z.string().optional().describe("Spec path template, e.g. /rest/projects/{id}/tasks"),
	pathParams: z
		.record(z.union([z.string(), z.number()]))
		.optional()
		.describe("Values for {placeholders} in the path."),
	query: z
		.record(z.union([z.string(), z.number(), z.boolean(), z.array(z.union([z.string(), z.number()]))]))
		.optional()
		.describe("Query-string parameters (page, pageSize, filters...)."),
	body: z.any().optional().describe("JSON request body for POST/PUT/PATCH."),
};

export const apiReadTool = {
	name: "unanet_api_read",
	description:
		"Execute any READ-classified Unanet API operation from the catalog (GET, or POST search/retrieve endpoints) and return the raw JSON. Refuses write/sensitive operations. Use unanet_api_describe_operation first to learn the parameters. Large responses are truncated.",
	inputSchema: z.object(executeCommonFields),
	handler: async (args: any, auth: UnanetAuth) => {
		try {
			const op = findOperation(args);
			if (!op) {
				return { success: false, error: "Operation not found in the catalog. Search for it first." };
			}
			if (op.kind !== "read") {
				return {
					success: false,
					error: `${op.method} ${op.path} is classified as '${op.kind}', not read. Use a dedicated tool or the Unanet UI.`,
				};
			}
			const filled = fillPath(op.path, args.pathParams);
			if (!filled.ok) return { success: false, error: filled.error, operation: summarizeOperation(op) };
			const client = createUnanetClient(auth);
			const response = await client.request({
				method: op.method.toLowerCase() as any,
				url: clientPath(filled.path),
				params: args.query,
				data: op.method === "GET" ? undefined : (args.body ?? {}),
			});
			const { data, truncated } = truncateResponse(response.data);
			return {
				success: true,
				operation: summarizeOperation(op),
				status: response.status,
				truncated,
				data,
			};
		} catch (error) {
			return errorResult(error);
		}
	},
};
